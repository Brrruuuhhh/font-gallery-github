-- Сведения о шрифтах хранятся отдельно от файлов, поэтому запросы списка каталога не загружают содержимое файлов.
CREATE TABLE IF NOT EXISTS fonts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug varchar(100) NOT NULL UNIQUE,
    name varchar(150) NOT NULL,
    family varchar(20) NOT NULL CHECK (family IN ('serif', 'sans-serif', 'monospace', 'display', 'handwriting')),
    author varchar(250) NOT NULL,
    license varchar(20) NOT NULL CHECK (license IN ('OFL', 'UFL', 'free', 'commercial', 'SIL')),
    license_text text NOT NULL,
    source_url text NOT NULL,
    preview_text varchar(500) NOT NULL,
    date_added date NOT NULL,
    downloads bigint NOT NULL DEFAULT 0 CHECK (downloads >= 0),
    supports_cyrillic boolean NOT NULL DEFAULT false,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS tags (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS font_tags (
    font_id bigint NOT NULL REFERENCES fonts(id) ON DELETE CASCADE,
    tag_id bigint NOT NULL REFERENCES tags(id) ON DELETE CASCADE,
    PRIMARY KEY (font_id, tag_id)
);

CREATE TABLE IF NOT EXISTS font_faces (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    font_id bigint NOT NULL REFERENCES fonts(id) ON DELETE CASCADE,
    weight smallint NOT NULL CHECK (weight BETWEEN 100 AND 900),
    style varchar(10) NOT NULL CHECK (style IN ('normal', 'italic', 'oblique')),
    UNIQUE (font_id, weight, style)
);

CREATE TABLE IF NOT EXISTS font_files (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    face_id bigint NOT NULL REFERENCES font_faces(id) ON DELETE CASCADE,
    format varchar(5) NOT NULL CHECK (format IN ('ttf', 'otf', 'woff', 'woff2')),
    file_name varchar(150) NOT NULL,
    mime_type varchar(30) NOT NULL,
    size_bytes integer NOT NULL CHECK (size_bytes > 0 AND size_bytes <= 20971520),
    sha256 char(64) NOT NULL CHECK (sha256 ~ '^[a-f0-9]{64}$'),
    source_url text NOT NULL,
    content bytea NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (face_id, format),
    CHECK (octet_length(content) = size_bytes)
);

CREATE INDEX IF NOT EXISTS fonts_date_added_idx ON fonts(date_added DESC, id);
CREATE INDEX IF NOT EXISTS fonts_family_license_idx ON fonts(family, license);
CREATE INDEX IF NOT EXISTS font_tags_tag_id_idx ON font_tags(tag_id);

CREATE OR REPLACE FUNCTION touch_font_modified() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at = clock_timestamp();
    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION touch_related_font() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    affected_font_id bigint;
BEGIN
    IF TG_TABLE_NAME = 'font_files' THEN
        SELECT font_id INTO affected_font_id FROM font_faces
        WHERE id = CASE WHEN TG_OP = 'DELETE' THEN OLD.face_id ELSE NEW.face_id END;
    ELSE
        affected_font_id = CASE WHEN TG_OP = 'DELETE' THEN OLD.font_id ELSE NEW.font_id END;
    END IF;
    UPDATE fonts SET updated_at = clock_timestamp() WHERE id = affected_font_id;
    RETURN NULL;
END;
$$;

CREATE OR REPLACE TRIGGER fonts_modified BEFORE UPDATE ON fonts
FOR EACH ROW EXECUTE FUNCTION touch_font_modified();
CREATE OR REPLACE TRIGGER files_modified BEFORE UPDATE ON font_files
FOR EACH ROW EXECUTE FUNCTION touch_font_modified();
CREATE OR REPLACE TRIGGER files_touch_font AFTER INSERT OR UPDATE OR DELETE ON font_files
FOR EACH ROW EXECUTE FUNCTION touch_related_font();
CREATE OR REPLACE TRIGGER tags_touch_font AFTER INSERT OR UPDATE OR DELETE ON font_tags
FOR EACH ROW EXECUTE FUNCTION touch_related_font();
CREATE OR REPLACE TRIGGER faces_touch_font AFTER INSERT OR UPDATE OR DELETE ON font_faces
FOR EACH ROW EXECUTE FUNCTION touch_related_font();

